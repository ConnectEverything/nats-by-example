#!/usr/bin/env bash
# Regenerates docker/go/deps.go from the imports of the Go examples that share
# docker/go/go.mod (those without their own go.mod).
#
# docker/go/main.go is only a placeholder that each example's main.go
# replaces at build time, so without deps.go `go mod tidy` in docker/go would
# drop every dependency the placeholder doesn't import and break the
# examples that need them. deps.go is excluded from normal builds by a build
# tag, but `go mod tidy` still sees its imports.
set -euo pipefail

cd "$(dirname "$0")/.."

out=docker/go/deps.go

imports="$(
  for d in examples/*/*/go; do
    [ -f "$d/go.mod" ] && continue
    for f in "$d"/*.go; do
      [ -f "$f" ] || continue
      # Single-line imports and import blocks.
      awk '
        /^import[[:space:]]*\(/ { in_block = 1; next }
        in_block && /^\)/       { in_block = 0; next }
        in_block                { print; next }
        /^import[[:space:]]/    { print }
      ' "$f"
    done
  done | grep -oE '"[^"]+"' | tr -d '"' \
       | awk -F/ 'index($1, ".") > 0' | sort -u
)"

{
  echo "//go:build deps"
  echo ""
  echo "// Code generated by scripts/sync-go-deps.sh. DO NOT EDIT."
  echo ""
  echo "// Package main records the third-party packages used by the Go examples"
  echo "// that share this module, so that go mod tidy keeps them in go.mod."
  echo "package main"
  echo ""
  echo "import ("
  while IFS= read -r imp; do
    [ -n "$imp" ] && printf '\t_ "%s"\n' "$imp"
  done <<< "$imports"
  echo ")"
} > "$out"

gofmt -w "$out"
echo "wrote $out:"
sed -n '/^import/,/^)/p' "$out"
